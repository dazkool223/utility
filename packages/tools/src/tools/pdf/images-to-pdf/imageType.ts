export type EmbeddableType = 'jpeg' | 'png';

/** Identify JPEG and PNG by their first bytes. Anything else must be decoded and re-encoded as PNG first. */
export function detectImageType(bytes: Uint8Array): EmbeddableType | null {
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return 'jpeg';
  if (bytes.length >= 8 && bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47 && bytes[4] === 0x0d && bytes[5] === 0x0a && bytes[6] === 0x1a && bytes[7] === 0x0a) {
    return 'png';
  }
  return null;
}
